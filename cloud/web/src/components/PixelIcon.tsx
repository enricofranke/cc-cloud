export function PixelIcon({ name, size = 16, class: cls }: { name: IconName | string | undefined; size?: number; class?: string }) {
  const map = name && (MAPS as Record<string, string[]>)[name];
  if (!map) return null;
  const rects = [];
  for (let y = 0; y < 8; y++) {
    const row = map[y];
    let x = 0;
    while (x < 8) {
      if (row[x] !== "#") {
        x++;
        continue;
      }
      let w = 1;
      while (x + w < 8 && row[x + w] === "#") w++;
      rects.push(<rect key={`${x}-${y}`} x={x} y={y} width={w} height={1} />);
      x += w;
    }
  }
  return (
    <svg class={`px-icon ${cls ?? ""}`} width={size} height={size} viewBox="0 0 8 8" shape-rendering="crispEdges" fill="currentColor" aria-hidden="true">
      {rects}
    </svg>
  );
}
