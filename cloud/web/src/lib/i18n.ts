export const STRINGS: Record<Lang, Record<Key, string>> = { en: EN, de: DE };

/** The string in a language, with {placeholders} filled. */
export function tr(l: Lang, key: Key, vars?: Record<string, string | number>): string {
  const s = STRINGS[l][key] ?? STRINGS.en[key] ?? key;
  return vars ? s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`)) : s;
}
/** The string in the current language (components re-render when it changes). */
export const t = (key: Key, vars?: Record<string, string | number>) => tr(lang.value, key, vars);
/** Locale for numbers and dates. */
export const locale = (l: Lang = lang.value) => (l === "de" ? "de-DE" : "en-US");
