// docs' language preference ("lang": the docs' language switch or the settings sheet; else the browser).
// The older dashboard screens are English-only. `t("key", {n: 3})` fills {n} placeholders.
import { signal } from "@preact/signals";
import { getPref, setPref } from "./store.ts";
import { detectLang, type Lang } from "./lang.ts";

export type { Lang };

const initialLang = (): Lang => {
  const saved = getPref("lang", "");
  return saved === "de" || saved === "en" ? saved : detectLang();
};
/** The current language (shared with the docs). */
export const lang = signal<Lang>(initialLang());
export function setLang(l: Lang) {
  lang.value = l;
  setPref("lang", l);
  if (typeof document !== "undefined") document.documentElement.lang = l;
}

