const DICT: Record<Lang, Record<CodeKey, string>> = { en: EN, de: DE };

export function ctr(l: Lang, key: CodeKey, vars?: Record<string, string | number>): string {
  const s = DICT[l][key] ?? EN[key];
  return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
}
export const hasKey = (k: string): k is CodeKey => k in EN;
/** In the current dashboard language. */
export const ct = (key: CodeKey, vars?: Record<string, string | number>) => ctr(lang.value, key, vars);

/** A server error code (with its detail) as a sentence. */
export function codeErrText(e: unknown): string {
  const x = e as Error & { detail?: string };
  const key = `err.${x.message}`;
  const base = hasKey(key) ? ct(key) : x.message;
  return x.detail && x.message !== "changed" ? `${base}: ${x.detail}` : base;
}
